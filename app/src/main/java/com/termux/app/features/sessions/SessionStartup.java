package com.termux.app.features.sessions;

import android.content.Context;
import android.system.Os;

import androidx.annotation.NonNull;
import androidx.annotation.Nullable;
import androidx.annotation.RawRes;

import com.termux.R;
import com.termux.app.TermuxService;
import com.termux.app.features.TermuxCommandRunner;
import com.termux.shared.logger.Logger;
import com.termux.shared.shell.command.ExecutionCommand;
import com.termux.shared.termux.TermuxConstants;
import com.termux.shared.termux.shell.TermuxShellManager;
import com.termux.shared.termux.shell.command.runner.terminal.TermuxSession;

import java.io.ByteArrayOutputStream;
import java.io.File;
import java.io.FileInputStream;
import java.io.FileOutputStream;
import java.io.IOException;
import java.io.InputStream;
import java.nio.charset.StandardCharsets;
import java.util.ArrayList;
import java.util.List;

/**
 * Starts terminal sessions for {@link TerminalProfile}s and runs startup commands, global and per
 * profile, when sessions start, see {@link SessionLaunchPlan}.
 *
 * The startup commands are written to files under ~/.termux/re/ that are sourced by the shell of
 * the session, the user's dotfiles are not changed. Failsafe sessions and sessions started by
 * plugins or for commands don't run startup commands.
 */
public final class SessionStartup {

    private static final String LOG_TAG = "SessionStartup";

    /** The directory of the generated files, ~/.termux/re. */
    public static final String DIR_PATH = TermuxConstants.TERMUX_HOME_DIR_PATH + "/.termux/re";
    public static final String GLOBAL_STARTUP_FILE_PATH = DIR_PATH + "/startup.sh";
    public static final String PROFILES_DIR_PATH = DIR_PATH + "/profiles";
    public static final String SHELL_DIR_PATH = DIR_PATH + "/shell";

    private static final SessionLaunchPlan.Paths PATHS = new SessionLaunchPlan.Paths(
        TermuxConstants.TERMUX_BIN_PREFIX_DIR_PATH, SHELL_DIR_PATH);

    private static final String STARTUP_FILE_HEADER = "# Generated by Termux RE from %s, changes are overwritten.\n" +
        "# Sourced by the shell of new terminal sessions after its startup files.\n\n";

    private SessionStartup() {}

    /**
     * Create a session.
     *
     * @param profile The profile to start the session with, or {@code null}.
     * @param sessionName The session name, or {@code null} for the profile name.
     * @param workingDirectory The working directory if the profile has none, or {@code null}.
     */
    @Nullable
    public static TermuxSession createSession(@NonNull Context context, @NonNull TermuxService service,
                                              @Nullable TerminalProfile profile, @Nullable String sessionName,
                                              @Nullable String workingDirectory) {
        if (profile != null) {
            String profileDirectory = resolveWorkingDirectory(profile.workingDirectory);
            if (profileDirectory != null) workingDirectory = profileDirectory;
            if (sessionName == null && !profile.name.trim().isEmpty()) sessionName = profile.name.trim();
        }

        SessionLaunchPlan plan = createLaunchPlan(context, profile);
        ExecutionCommand executionCommand = new ExecutionCommand(TermuxShellManager.getNextShellId(),
            plan == null ? null : plan.executable, plan == null ? null : plan.arguments, null, workingDirectory,
            ExecutionCommand.Runner.TERMINAL_SESSION.getName(), false);
        executionCommand.shellName = sessionName;

        TermuxSession session = service.createTermuxSession(executionCommand, plan == null ? null : plan.environment);
        if (session != null && profile != null) SessionRegistry.get(session.getTerminalSession()).profileId = profile.id;
        return session;
    }

    /** Create the launch plan for a session, or {@code null} to start it like a normal session. */
    @Nullable
    static SessionLaunchPlan createLaunchPlan(@NonNull Context context, @Nullable TerminalProfile profile) {
        if (!TermuxCommandRunner.isBootstrapInstalled()) return null;

        String defaultShell = resolveDefaultShell();
        String shell = defaultShell;
        if (profile != null && !profile.shell.isEmpty()) {
            File profileShell = new File(TermuxConstants.TERMUX_BIN_PREFIX_DIR_PATH, profile.shell);
            if (profileShell.canExecute())
                shell = profileShell.getAbsolutePath();
            else
                Logger.logWarn(LOG_TAG, "The shell \"" + profile.shell + "\" of the profile \"" + profile.name + "\" is not installed");
        }
        boolean useLogin = canonicalPath(shell).equals(canonicalPath(defaultShell)) &&
            new File(TermuxConstants.TERMUX_BIN_PREFIX_DIR_PATH, "login").canExecute();

        List<String> startupFiles = new ArrayList<>();
        String globalCommands = SessionsPreferences.getStartupCommands(context);
        if (!globalCommands.trim().isEmpty() &&
            writeStartupFile(GLOBAL_STARTUP_FILE_PATH, context.getString(R.string.feature_sessions_startup_global_source), globalCommands))
            startupFiles.add(GLOBAL_STARTUP_FILE_PATH);
        if (profile != null && !profile.startupCommands.trim().isEmpty() && writeProfileStartupFile(profile))
            startupFiles.add(getProfileStartupFilePath(profile.id));

        int notifyAfter = SessionsPreferences.areNotificationsEnabled(context) && SessionsPreferences.isNotifyCommandsEnabled(context) ?
            SessionsPreferences.getNotifyCommandsSeconds(context) : 0;

        SessionLaunchPlan plan = SessionLaunchPlan.create(PATHS, shell, useLogin, startupFiles, notifyAfter,
            profile == null ? null : profile.name);
        if (!plan.environment.isEmpty() || plan.executable != null) writeShellFiles(context);
        return plan;
    }

    /** Get the shell the login command starts: ~/.termux/shell, or bash or sh in $PREFIX/bin. */
    @NonNull
    public static String resolveDefaultShell() {
        File userShell = new File(TermuxConstants.TERMUX_HOME_DIR_PATH, ".termux/shell");
        if (userShell.exists()) {
            String path = canonicalPath(userShell.getAbsolutePath());
            if (new File(path).canExecute()) return path;
        }
        for (String shell : new String[]{"bash", "sh"}) {
            File file = new File(TermuxConstants.TERMUX_BIN_PREFIX_DIR_PATH, shell);
            if (file.canExecute()) return file.getAbsolutePath();
        }
        return "/system/bin/sh";
    }

    /** Get the names of the {@link TerminalProfile#SHELLS} that are installed. */
    @NonNull
    public static List<String> getInstalledShells() {
        List<String> shells = new ArrayList<>();
        for (String shell : TerminalProfile.SHELLS) {
            if (new File(TermuxConstants.TERMUX_BIN_PREFIX_DIR_PATH, shell).canExecute()) shells.add(shell);
        }
        return shells;
    }

    /** Get the directory {@code path}, with "~" expanded, or {@code null} if it is empty or does not exist. */
    @Nullable
    public static String resolveWorkingDirectory(@Nullable String path) {
        String expanded = expandHome(path);
        if (expanded == null) return null;
        if (!new File(expanded).isDirectory()) {
            Logger.logWarn(LOG_TAG, "The working directory \"" + expanded + "\" does not exist");
            return null;
        }
        return expanded;
    }

    /** Expand "~" and "$HOME" at the start of {@code path}, or return {@code null} if it is empty. */
    @Nullable
    static String expandHome(@Nullable String path) {
        if (path == null || path.trim().isEmpty()) return null;
        path = path.trim();
        String home = TermuxConstants.TERMUX_HOME_DIR_PATH;
        if (path.equals("~") || path.equals("$HOME")) return home;
        if (path.startsWith("~/")) return home + path.substring(1);
        if (path.startsWith("$HOME/")) return home + path.substring(5);
        return path;
    }

    @NonNull
    public static String getProfileStartupFilePath(@NonNull String profileId) {
        // Profile ids are generated UUIDs, but don't allow other paths.
        return PROFILES_DIR_PATH + "/" + profileId.replaceAll("[^A-Za-z0-9_-]", "_") + ".sh";
    }

    /** Write the startup file of {@code profile}, or delete it if it has no startup commands. */
    static boolean writeProfileStartupFile(@NonNull TerminalProfile profile) {
        String path = getProfileStartupFilePath(profile.id);
        if (profile.startupCommands.trim().isEmpty()) {
            deleteFile(path);
            return false;
        }
        return writeStartupFile(path, "profile \"" + profile.name.replace("\n", " ") + "\"", profile.startupCommands);
    }

    static void deleteProfileStartupFile(@NonNull String profileId) {
        deleteFile(getProfileStartupFilePath(profileId));
    }

    /** Write the global startup file, or delete it if there are no global startup commands. */
    public static void writeGlobalStartupFile(@NonNull Context context) {
        String commands = SessionsPreferences.getStartupCommands(context);
        if (commands.trim().isEmpty())
            deleteFile(GLOBAL_STARTUP_FILE_PATH);
        else
            writeStartupFile(GLOBAL_STARTUP_FILE_PATH, context.getString(R.string.feature_sessions_startup_global_source), commands);
    }

    private static boolean writeStartupFile(@NonNull String path, @NonNull String source, @NonNull String commands) {
        if (!TermuxCommandRunner.isBootstrapInstalled()) return false;
        return writeFileIfChanged(path, String.format(STARTUP_FILE_HEADER, source) + commands.replace("\r\n", "\n") + "\n");
    }

    /** Write the shell init scripts used by {@link SessionLaunchPlan}. */
    private static void writeShellFiles(@NonNull Context context) {
        writeShellFile(context, R.raw.feature_sessions_init_bash, PATHS.bashInit());
        writeShellFile(context, R.raw.feature_sessions_init_zsh, PATHS.zshInit());
        writeShellFile(context, R.raw.feature_sessions_zshenv, PATHS.zshDotDir() + "/.zshenv");
        writeShellFile(context, R.raw.feature_sessions_init_fish, PATHS.fishInit());
        writeShellFile(context, R.raw.feature_sessions_init_sh, PATHS.shInit());
        writeShellFile(context, R.raw.feature_sessions_login_shell, PATHS.loginShellScript());
    }

    private static void writeShellFile(@NonNull Context context, @RawRes int resource, @NonNull String path) {
        String text = readRawResource(context, resource);
        if (text == null) return;
        text = text.replace("@BASH_PROMPT_COMMAND@", PATHS.bashPromptCommand())
            .replace("@SHELL_DIR@", SHELL_DIR_PATH)
            .replace("@TERMUX_PREFIX@", TermuxConstants.TERMUX_PREFIX_DIR_PATH);
        writeFileIfChanged(path, text);
    }

    @Nullable
    private static String readRawResource(@NonNull Context context, @RawRes int resource) {
        try (InputStream in = context.getResources().openRawResource(resource)) {
            return readFully(in);
        } catch (IOException e) {
            Logger.logStackTraceWithMessage(LOG_TAG, "Failed to read resource " + resource, e);
            return null;
        }
    }

    /**
     * Write {@code text} to {@code path} if it has other content. The files and directories under
     * {@link #DIR_PATH} are only readable by the app user.
     */
    static boolean writeFileIfChanged(@NonNull String path, @NonNull String text) {
        File file = new File(path);
        try {
            if (file.isFile()) {
                try (InputStream in = new FileInputStream(file)) {
                    if (text.equals(readFully(in))) return true;
                }
            }
            createPrivateDirectories(file.getParentFile());
            File tempFile = new File(path + ".tmp");
            try (FileOutputStream out = new FileOutputStream(tempFile)) {
                out.write(text.getBytes(StandardCharsets.UTF_8));
            }
            chmod(tempFile, 0600);
            if (!tempFile.renameTo(file)) throw new IOException("Failed to rename " + tempFile + " to " + file);
            return true;
        } catch (IOException e) {
            Logger.logStackTraceWithMessage(LOG_TAG, "Failed to write " + path, e);
            return false;
        }
    }

    private static void createPrivateDirectories(@Nullable File directory) throws IOException {
        if (directory == null || directory.isDirectory()) return;
        createPrivateDirectories(directory.getParentFile());
        if (!directory.mkdir() && !directory.isDirectory()) throw new IOException("Failed to create " + directory);
        if (directory.getAbsolutePath().startsWith(DIR_PATH)) chmod(directory, 0700);
    }

    private static void chmod(@NonNull File file, int mode) {
        try {
            Os.chmod(file.getAbsolutePath(), mode);
        } catch (Exception e) {
            Logger.logWarn(LOG_TAG, "Failed to chmod " + file + ": " + e.getMessage());
        }
    }

    private static void deleteFile(@NonNull String path) {
        File file = new File(path);
        if (file.exists() && !file.delete()) Logger.logWarn(LOG_TAG, "Failed to delete " + path);
    }

    @NonNull
    private static String readFully(@NonNull InputStream in) throws IOException {
        ByteArrayOutputStream out = new ByteArrayOutputStream();
        byte[] buffer = new byte[8192];
        int read;
        while ((read = in.read(buffer)) != -1) out.write(buffer, 0, read);
        return new String(out.toByteArray(), StandardCharsets.UTF_8);
    }

    @NonNull
    private static String canonicalPath(@NonNull String path) {
        try {
            return new File(path).getCanonicalPath();
        } catch (IOException e) {
            return path;
        }
    }

}
